# Generates src/ok_credentials.h from an OKLumessenger-style credentials.cfg
# (OK_APP_KEY, OK_APP_SECRET, OK_USER_AGENT). The values are XOR-masked so they are not
# stored as plain text in the repository - this is obfuscation, not protection.
#
#   python mask_credentials.py D:\github\OKLumessenger\credentials.cfg

import os, random, sys

NAMES = ('OK_APP_KEY', 'OK_APP_SECRET', 'OK_USER_AGENT')

if len(sys.argv) != 2:
    sys.exit('usage: mask_credentials.py <credentials.cfg>')

vals = {}
for line in open(sys.argv[1], encoding='utf-8'):
    line = line.strip()
    if line and not line.startswith('#') and '=' in line:
        k, v = line.split('=', 1)
        vals[k.strip()] = v.strip()

missing = [n for n in NAMES if not vals.get(n)]
if missing:
    sys.exit('missing in credentials.cfg: ' + ', '.join(missing))

def mask(text, seed):
    out = []
    for i, b in enumerate(text.encode('utf-8')):
        out.append(b ^ ((seed + i * 0x3D) & 0xFF))
    return out

lines = ['// Generated by mask_credentials.py - do not edit. The Odnoklassniki application key, secret and',
         '// User-Agent, XOR-masked so they are not plain text in the repository (obfuscation only).',
         '',
         '#pragma once',
         '',
         'namespace okcred',
         '{',
         '	inline std::string Unmask(const unsigned char *data, size_t len, unsigned char seed)',
         '	{',
         '		std::string s(len, 0);',
         '		for (size_t i = 0; i < len; i++)',
         '			s[i] = char(data[i] ^ (unsigned char)(seed + i * 0x3D));',
         '		return s;',
         '	}',
         '']
rnd = random.SystemRandom()
for n in NAMES:
    seed = rnd.randrange(1, 256)
    data = mask(vals[n], seed)
    ident = n[3:].lower()  # app_key, app_secret, user_agent
    rows = [', '.join('0x%02X' % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    lines.append('	const unsigned char %s[%d] = {' % (ident, len(data)))
    lines += ['		%s,' % r for r in rows]
    lines.append('	};')
    lines.append('	inline const char* %s_str() { static const std::string s = Unmask(%s, sizeof(%s), 0x%02X); return s.c_str(); }' % (ident, ident, ident, seed))
    lines.append('')
lines.append('}')
lines.append('')
for n in NAMES:
    lines.append('#define %-14s okcred::%s_str()' % (n, n[3:].lower()))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'src', 'ok_credentials.h')
with open(out, 'w', encoding='utf-8', newline='\r\n') as f:
    f.write('\n'.join(lines) + '\n')
print('written', out)
